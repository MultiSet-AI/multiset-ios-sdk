import AVFoundation

enum MappingCameraAccess {

    /// The prompt is raised here, never by running the AR session: ARKit does not re-run its
    /// configuration once the prompt is answered, which leaves a black camera on first launch.
    static func authorize() async -> Bool {
        switch AVCaptureDevice.authorizationStatus(for: .video) {
        case .authorized:
            return true
        case .notDetermined:
            return await AVCaptureDevice.requestAccess(for: .video)
        default:
            return false
        }
    }
}
